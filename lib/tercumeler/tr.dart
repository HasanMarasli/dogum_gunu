String tZodiac(String sign, String section, Map<String, String> translations) =>
    translations['zodiac.$sign.$section'] ?? '-';

List<String> tZodiacList(
  String sign,
  String section,
  Map<String, String> translations,
) {
  final raw = tZodiac(sign, section, translations);
  return raw
      .split('\n')
      .map((e) => e.trim())
      .where((e) => e.isNotEmpty)
      .map((e) => e.startsWith('• ') ? e.substring(2) : e)
      .toList();
}

